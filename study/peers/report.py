"""Write data/out/latency/peers.md from the peers_*.csv tables.

    python3 study/peers/report.py"""
from __future__ import annotations

import pandas as pd

from bursts import BURST_S, ROOT
from findings import BINS, early_late, headline
from follow import DIR_S
from tables import (FOL_AGREE, FOL_USD, FOL_Z, OP_PNL, OP_Q, followers, operator_groups,
                    population, rank_corr, rank_table)

OUT = ROOT / "data" / "out" / "latency"
SHORT = lambda s: s.replace("btc-up-or-down-", "")  # noqa: E731


def md(df: pd.DataFrame, fmt: dict[str, str]) -> str:
    cols = list(fmt)
    out = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    for _, r in df.iterrows():
        out.append("| " + " | ".join(fmt[c].format(r[c]) if pd.notna(r[c]) else "" for c in cols) + " |")
    return "\n".join(out)


def load() -> dict[str, pd.DataFrame]:
    names = ["speed", "pairs", "followers", "lagcurve", "followcurve", "opcorr"]
    d = {n: pd.read_csv(OUT / f"peers_{n}.csv") for n in names}
    d["wallets"] = pd.read_csv(OUT / "wallets.csv")
    return d


RANK_FMT = {"pnl_rank": "{:d}", "speed_rank": "{:.0f}", "wallet": "{}", "latency_class": "{}",
            "pnl": "{:+,.0f}", "roi": "{:.1%}", "contested": "{:,.0f}", "first_share": "{:.2f}",
            "duel": "{:+.3f}", "mean_lag": "{:.2f}", "gap_c": "{:.2f}", "edge_l0": "{:+.3f}"}


def main() -> None:
    d = load()
    r = rank_table(d["speed"], d["pairs"])
    r.to_csv(OUT / "peers_rank.csv", index=False, float_format="%.6g")
    rc = rank_corr(r)
    og = operator_groups(d["opcorr"], d["wallets"])
    og.to_csv(OUT / "peers_operators.csv", index=False, float_format="%.6g")
    fo = followers(d["followers"])
    pop = population(d["followers"])
    lc = d["lagcurve"][d["lagcurve"]["lag"] <= 5]
    fc = d["followcurve"].assign(o=lambda x: x["bin"].map(BINS.index)).sort_values(["series", "o"])
    el = early_late(d["lagcurve"])
    L = []
    L += ["# Latency bots: peers, followers, operators", "",
          "Generated by `python3 study/peers` then `python3 study/peers/report.py`.",
          f"Burst = latency-style taker fills on one (market, side) within {BURST_S} s of the first one "
          "(latency-style = latency_arb, latency_arb_partial or momentum_taker in that family). "
          "Lag is measured on Polygon block timestamps, so 0 means same block as the first mover.", ""]
    L += headline(r, rc, og, fo, pop, el, d["wallets"])
    L += ["## Speed vs profit, per family", "",
          "`duel` = over every head-to-head co-burst, share strictly earlier minus share strictly later. "
          "`first_share` = share of contested bursts in the first block. `gap_c` = USD-weighted cents paid "
          "above the first-mover price. `edge_l0` = PnL per USD of its first-block burst entries. "
          "Speed rank is by duel. Wallets with >= 100 contested bursts.", ""]
    L += [md(rc.assign(series=rc["series"].map(SHORT)),
             {"series": "{}", "wallets": "{:d}", "rho_speed_pnl": "{:+.2f}", "rho_speed_roi": "{:+.2f}",
              "rho_first_pnl": "{:+.2f}", "rho_edge0_roi": "{:+.2f}", "arb_wallets": "{:d}",
              "rho_speed_pnl_arb": "{:+.2f}"}), ""]
    for fam in ["btc-up-or-down-5m", "btc-up-or-down-15m", "btc-up-or-down-hourly",
                "btc-up-or-down-4h", "btc-up-or-down-daily"]:
        x = r[r["series"] == fam].head(15)
        L += [f"### {SHORT(fam)} (top {len(x)} by PnL of {int((r['series'] == fam).sum())})", "",
              md(x, RANK_FMT), ""]
    top5 = r[(r["series"] == "btc-up-or-down-5m")].head(5)["wallet"].tolist()
    p5 = d["pairs"][(d["pairs"]["series"] == "btc-up-or-down-5m") & d["pairs"]["a"].isin(top5)
                    & d["pairs"]["b"].isin(top5)]
    L += ["### Head-to-head, top 5 by PnL in 5m", "",
          md(p5, {"a": "{}", "b": "{}", "co_bursts": "{:,.0f}", "a_first": "{:.2f}", "tie": "{:.2f}",
                  "b_first": "{:.2f}", "size_corr": "{:+.2f}"}), ""]
    L += ["### First block vs 1-5 s late (all latency-style burst entries)", "",
          md(el.assign(series=el["series"].map(SHORT)),
             {"series": "{}", "usd_first": "{:,.0f}", "pnl_per_usd_first": "{:+.4f}",
              "gap_c_first": "{:.2f}", "usd_late": "{:,.0f}", "pnl_per_usd_late": "{:+.4f}",
              "gap_c_late": "{:.2f}"}), ""]
    L += ["### Edge of a burst entry by lag (all latency-style wallets)", "",
          md(lc.assign(series=lc["series"].map(SHORT)),
             {"series": "{}", "lag": "{:d}", "entries": "{:,.0f}", "usd": "{:,.0f}",
              "pnl_per_usd": "{:+.4f}", "gap_c": "{:.2f}"}), ""]
    L += ["## Operator groups", "",
          f"Edge = per-market net position corr >= {OP_Q} AND per-market PnL corr >= {OP_PNL} over >= 30 "
          "shared markets (95th percentile of all latency pairs is 0.23-0.41 in 5m/15m). "
          "btc_pnl sums every BTC family of each member.", "",
          md(og, {"n": "{:d}", "btc_pnl": "{:+,.0f}", "families": "{}", "q_corr_min": "{:.2f}",
                  "pnl_corr_min": "{:.2f}", "members": "{}"}), ""]
    L += ["## Followers", "",
          f"Direction test: of a non-latency wallet's taker USD whose most recent latency burst on that "
          f"market came 1-{DIR_S} s earlier, the share on the SAME side as that burst (0.5 = blind). "
          f"Follower = z >= {FOL_Z:g}, agree >= {FOL_AGREE}, >= ${FOL_USD:,.0f} in the test window. "
          "pnl = taker PnL in that family.", "",
          md(pop.assign(series=pop["series"].map(SHORT)),
             {"series": "{}", "wallets": "{:d}", "dir_agree_usd": "{:.3f}", "z_ge_4": "{:d}",
              "z_le_-4": "{:d}"}), "",
          f"{len(fo)} follower rows ({fo['wallet'].nunique()} wallets), taker PnL {fo['pnl'].sum():+,.0f} "
          f"on ${fo['usd'].sum():,.0f}, {(fo['pnl'] > 0).mean():.0%} profitable.", "",
          md(fo.assign(series=fo["series"].map(SHORT)),
             {"wallet": "{}", "series": "{}", "fills": "{:,.0f}", "usd": "{:,.0f}", "pnl": "{:+,.0f}",
              "dir_agree": "{:.2f}", "dir_z": "{:.1f}", "co_move": "{:.2f}", "med_lag_same": "{:.0f}"}), "",
          "### What entering after a burst earns (all non-latency taker fills)", "",
          md(fc.assign(series=fc["series"].map(SHORT)),
             {"series": "{}", "bin": "{}", "fills": "{:,.0f}", "usd": "{:,.0f}", "pnl_per_usd": "{:+.4f}"}),
          ""]
    (OUT / "peers.md").write_text("\n".join(L))
    print(rc.round(3).to_string())


if __name__ == "__main__":
    main()
